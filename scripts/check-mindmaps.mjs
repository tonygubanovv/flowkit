import assert from 'node:assert/strict';
import { createServer } from 'vite';

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
try {
  const { normalizeMindMaps, createMindMap, projectMindMapData, upsertMindMap, removeMindMap, normalizeMindMapUrl } = await server.ssrLoadModule('/src/lib/MindMaps.ts');
  const { makeDefaultData, normalizeImportedData } = await server.ssrLoadModule('/src/data/DefaultData.ts');
  const { sanitizeAppDataForExport } = await server.ssrLoadModule('/src/data/AppStorage.ts');
  const data = makeDefaultData();
  const map = createMindMap('map', 'root', 'p1');
  const pdf = 'data:application/pdf;base64,JVBERi0xLjQK';
  const image = 'data:image/png;base64,aGVsbG8=';
  map.data.nodeData.children = [{ id: 'task-node', topic: 'Старое название', metadata: { entity: { kind: 'task', id: 'task' }, attachments: [{ id: 'pdf', name: 'План.pdf', size: 9, dataUrl: pdf }] }, image: { url: image, width: 200, height: 140 }, hyperLink: 'https://example.com/' }, { id: 'note-node', topic: 'Старая заметка', metadata: { entity: { kind: 'note', id: 'note' } } }];
  map.data.arrows = [{ id: 'arrow', from: 'task-node', to: 'note-node', label: 'Связь', delta1: { x: 10, y: 20 } }];
  map.data.summaries = [{ id: 'summary', parent: 'root', start: 0, end: 1, label: 'Материалы' }];
  const task = { id: 'task', title: 'Актуальная задача', projectId: 'p1', columnId: 'c3', completed: false };
  const note = { id: 'note', title: 'Актуальная заметка' };
  const projected = projectMindMapData(map.data, [task], [note], data.projects);
  assert.equal(projected.nodeData.children[0].topic, task.title);
  assert.deepEqual(projected.nodeData.children[0].tags, ['Выполнена', 'PDF · 1']);
  assert.equal(projected.nodeData.children[1].topic, note.title);
  assert.equal(map.data.nodeData.children[0].topic, 'Старое название');
  const missing = projectMindMapData(map.data, [], [], data.projects);
  assert.deepEqual(missing.nodeData.children[0].tags, ['Связь недоступна', 'PDF · 1']);
  assert.equal(missing.nodeData.children[0].metadata.attachments[0].dataUrl, pdf);
  const updated = upsertMindMap(data, map);
  assert.equal(data.mindMaps, undefined);
  const restored = normalizeImportedData(JSON.parse(JSON.stringify(sanitizeAppDataForExport(updated))));
  assert.equal(restored.mindMaps[0].data.nodeData.children[0].metadata.attachments[0].dataUrl, pdf);
  assert.equal(restored.mindMaps[0].data.nodeData.children[0].image.url, image);
  assert.deepEqual(restored.mindMaps[0].data.arrows, map.data.arrows.map((arrow) => ({ ...arrow, bidirectional: false, delta2: undefined })));
  assert.equal(restored.mindMaps[0].data.summaries[0].label, 'Материалы');
  assert.equal(removeMindMap(updated, map.id).tasks, data.tasks);
  assert.equal(removeMindMap(updated, map.id).notes, data.notes);
  assert.deepEqual(normalizeMindMaps(undefined), []);
  assert.equal(normalizeMindMapUrl('javascript:alert(1)'), null);
  const unsafe = structuredClone(map);
  unsafe.data.nodeData.dangerouslySetInnerHTML = '<img src=x onerror=alert(1)>';
  unsafe.data.nodeData.style = { background: 'url(https://example.com/tracker)' };
  unsafe.data.nodeData.hyperLink = 'javascript:alert(1)';
  const cleaned = normalizeMindMaps([unsafe])[0].data.nodeData;
  assert.equal(cleaned.dangerouslySetInnerHTML, undefined);
  assert.equal(cleaned.style, undefined);
  assert.equal(cleaned.hyperLink, undefined);
  assert.throws(() => normalizeMindMaps([map, map]));
  const duplicate = structuredClone(map);
  duplicate.data.nodeData.children[0].id = 'root';
  assert.throws(() => normalizeMindMaps([duplicate]));
  console.log('Mind maps: migration, backup, entity projection, isolation and unsafe input checks passed.');
} finally { await server.close(); }
